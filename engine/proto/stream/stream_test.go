// newManager starts an engine.Manager with an in-memory store, a temp download folder and
// the given protocols registered.
func newManager(t *testing.T, protos ...engine.Protocol) *engine.Manager {
	t.Helper()
	st, err := engine.OpenStore(":memory:")
	if err != nil {
		t.Fatal(err)
	}
	s := engine.DefaultSettings()
	s.DownloadDir = t.TempDir()
	s.Proxy = "none"
	if err := st.SaveSettings(s); err != nil {
		t.Fatal(err)
	}
	m, err := engine.NewManager(st)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { m.Close(); st.Close() })
	for _, p := range protos {
		m.RegisterProtocol(p)
	}
	return m
}

// testProto returns a protocol with fast retries and no ffmpeg (unless withFFmpeg).
func testProto(p *Protocol, withFFmpeg bool) *Protocol {
	p.backoff = 10 * time.Millisecond
	p.poll = 50 * time.Millisecond
	if !withFFmpeg {
		p.ffmpeg = func() string { return "" }
	}
	return p
}

func waitFor(t *testing.T, m *engine.Manager, id string, want engine.Status, timeout time.Duration) engine.Download {
	t.Helper()
	deadline := time.Now().Add(timeout)
	for time.Now().Before(deadline) {
		d, err := m.Get(id)
		if err != nil {
			t.Fatal(err)
		}
		if d.Status == want {
			return d
		}
		if d.Status == engine.StatusError && want != engine.StatusError {
			t.Fatalf("download failed: %s", d.Error)
		}
		time.Sleep(10 * time.Millisecond)
	}
	d, _ := m.Get(id)
	t.Fatalf("timeout waiting for %s: status=%s err=%q downloaded=%d", want, d.Status, d.Error, d.Downloaded)
	return d
}

func waitBytes(t *testing.T, m *engine.Manager, id string, n int64) {
	t.Helper()
	deadline := time.Now().Add(10 * time.Second)
	for time.Now().Before(deadline) {
		d, _ := m.Get(id)
		if d.Downloaded >= n {
			return
		}
		if d.Status != engine.StatusDownloading && d.Status != engine.StatusQueued {
			t.Fatalf("status %s (%s) before %d bytes", d.Status, d.Error, n)
		}
		time.Sleep(5 * time.Millisecond)
	}
	t.Fatalf("no progress to %d bytes", n)
}

// payload is deterministic segment content.
func payload(name string, n int) []byte {
	b := make([]byte, n)
	for i := range b {
		b[i] = byte(i*7 + len(name)*13 + int(name[len(name)-1]))
	}
	copy(b, name)
	return b
}

// server serves fixed bodies by path, counts requests, can delay segments and require
// headers. Paths ending in .m3u8/.mpd may be generated by a func.
type server struct {
	*httptest.Server
	mu      sync.Mutex
	files   map[string][]byte
	dynamic map[string]func() []byte
	hits    map[string]int
	delay   time.Duration
	require map[string]string // header -> value every request must carry
	cookies []string          // Cookie header seen per request
}

func newServer(t *testing.T) *server {
	s := &server{files: map[string][]byte{}, dynamic: map[string]func() []byte{}, hits: map[string]int{}}
	s.Server = httptest.NewServer(http.HandlerFunc(s.serve))
	t.Cleanup(s.Close)
	return s
}

func (s *server) serve(w http.ResponseWriter, r *http.Request) {
	s.mu.Lock()
	s.hits[r.URL.Path]++
	s.cookies = append(s.cookies, r.Header.Get("Cookie"))
	for k, v := range s.require {
		if r.Header.Get(k) != v {
			s.mu.Unlock()
			http.Error(w, "forbidden", http.StatusForbidden)
			return
		}
	}
	body, ok := s.files[r.URL.Path]
	gen := s.dynamic[r.URL.Path]
	delay := s.delay
	s.mu.Unlock()
	if gen != nil {
		body, ok = gen(), true
	}
	if !ok {
		http.NotFound(w, r)
		return
	}
	if delay > 0 && !strings.HasSuffix(r.URL.Path, ".m3u8") {
		select {
		case <-time.After(delay):
		case <-r.Context().Done():
			return
		}
	}
	http.ServeContent(w, r, "", time.Time{}, bytes.NewReader(body))
}

func (s *server) with(fn func()) {
	s.mu.Lock()
	defer s.mu.Unlock()
	fn()
}

func (s *server) setDynamic(path string, gen func() []byte) {
	s.with(func() { s.dynamic[path] = gen })
}

func (s *server) set(path string, body []byte) {
	s.mu.Lock()
	s.files[path] = body
	s.mu.Unlock()
}

func (s *server) cookieList() []string {
	s.mu.Lock()
	defer s.mu.Unlock()
	return append([]string(nil), s.cookies...)
}

func (s *server) hitCount(path string) int {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.hits[path]
}

// mediaPlaylist builds a VOD media playlist for segments seg0..segN-1 under dir.
func mediaPlaylist(s *server, dir string, n, size int) (want []byte) {
	var b strings.Builder
	b.WriteString("#EXTM3U\n#EXT-X-VERSION:3\n#EXT-X-TARGETDURATION:2\n#EXT-X-MEDIA-SEQUENCE:0\n")
	for i := range n {
		name := fmt.Sprintf("%s/seg%d.ts", dir, i)
		data := payload(name, size)
		s.set(name, data)
		want = append(want, data...)
		fmt.Fprintf(&b, "#EXTINF:2.0,\nseg%d.ts\n", i)
	}
	b.WriteString("#EXT-X-ENDLIST\n")
	s.set(dir+"/index.m3u8", []byte(b.String()))
	return want
}

func checkFile(t *testing.T, d engine.Download, name string, want []byte) {
	t.Helper()
	if d.Filename != name {
		t.Fatalf("filename = %q, want %q", d.Filename, name)
	}
	got, err := os.ReadFile(d.Path())
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("content differs: got %d bytes, want %d", len(got), len(want))
	}
	if _, err := os.Stat(d.PartPath()); !os.IsNotExist(err) {
		t.Fatal("part file left behind")
	}
	if _, err := os.Stat(strings.TrimSuffix(d.PartPath(), engine.PartSuffix) + ".peregrine.tmp"); !os.IsNotExist(err) {
		t.Fatal("temp folder left behind")
	}
}

func TestMatch(t *testing.T) {
	h, d := NewHLS(Options{}), NewDASH(Options{})
	for _, c := range []struct {
		url       string
		hls, dash bool
	}{
		{"https://cdn.example.com/a/index.m3u8", true, false},
		{"https://cdn.example.com/a/INDEX.M3U8?token=abc&x=.mpd", true, false},
		{"http://example.com/manifest.mpd?sig=1", false, true},
		{"https://example.com/video.mp4", false, false},
		{"https://example.com/page?file=x.m3u8", false, false},
		{"ftp://example.com/index.m3u8", false, false},
		{"file:///C:/x/index.m3u8", false, false},
	} {
		if h.Match(c.url) != c.hls || d.Match(c.url) != c.dash {
			t.Errorf("%s: hls=%v dash=%v", c.url, h.Match(c.url), d.Match(c.url))
		}
	}
	if h.Kind() != "hls" || d.Kind() != "dash" {
		t.Fatal("kinds")
	}
}

// TestHLSMasterBestVariant: the highest-bandwidth variant is downloaded, the browser's
// headers go with every request, and without ffmpeg the output is the plain .ts.
func TestHLSMasterBestVariant(t *testing.T) {
	s := newServer(t)
	s.with(func() { s.require = map[string]string{"Cookie": "session=1", "Referer": "https://site.example/watch"} })
	mediaPlaylist(s, "/low", 3, 1000)
	want := mediaPlaylist(s, "/high", 5, 3000)
	mediaPlaylist(s, "/mid", 3, 2000)
	s.set("/v/master.m3u8", []byte(`#EXTM3U
#EXT-X-STREAM-INF:BANDWIDTH=200000,RESOLUTION=320x180
/low/index.m3u8
#EXT-X-STREAM-INF:BANDWIDTH=1500000,RESOLUTION=1280x720,CODECS="avc1.4d401f,mp4a.40.2"
../high/index.m3u8
#EXT-X-STREAM-INF:BANDWIDTH=800000,RESOLUTION=854x480
`+s.URL+`/mid/index.m3u8
`))
	m := newManager(t, testProto(NewHLS(Options{}), false))
	d, err := m.Add(engine.Request{URL: s.URL + "/v/master.m3u8", Headers: map[string]string{
		"Cookie": "session=1", "Referer": "https://site.example/watch"}})
	if err != nil {
		t.Fatal(err)
	}
	if d.Kind != "hls" {
		t.Fatalf("kind = %q", d.Kind)
	}
	done := waitFor(t, m, d.ID, engine.StatusCompleted, 10*time.Second)
	checkFile(t, done, "master.ts", want)
	if s.hitCount("/low/index.m3u8") != 0 || s.hitCount("/mid/index.m3u8") != 0 || s.hitCount("/low/seg0.ts") != 0 {
		t.Fatal("a lower variant was fetched")
	}
	if done.Size != int64(len(want)) {
		t.Fatalf("size = %d", done.Size)
	}
}

func encrypt(t *testing.T, plain, key, iv []byte) []byte {
	t.Helper()
	pad := aes.BlockSize - len(plain)%aes.BlockSize
	in := append(append([]byte{}, plain...), bytes.Repeat([]byte{byte(pad)}, pad)...)
	block, err := aes.NewCipher(key)
	if err != nil {
		t.Fatal(err)
	}
	out := make([]byte, len(in))
	cipher.NewCBCEncrypter(block, iv).CryptBlocks(out, in)
	return out
}

func TestHLSAES128(t *testing.T) {
	s := newServer(t)
	key1 := []byte("0123456789abcdef")
	key2 := []byte("fedcba9876543210")
	s.set("/keys/k1", key1)
	s.set("/keys/k2", key2)
	explicitIV := []byte("IVIVIVIVIVIVIVIV")
	var want []byte
	var pl strings.Builder
	pl.WriteString("#EXTM3U\n#EXT-X-TARGETDURATION:4\n#EXT-X-MEDIA-SEQUENCE:7\n")
	pl.WriteString(fmt.Sprintf("#EXT-X-KEY:METHOD=AES-128,URI=\"/keys/k1\",IV=0x%x\n", explicitIV))
	for i := range 6 {
		seq := int64(7 + i)
		if i == 3 { // second key, IV from the media sequence number
			pl.WriteString("#EXT-X-KEY:METHOD=AES-128,URI=\"../keys/k2\"\n")
		}
		if i == 5 {
			pl.WriteString("#EXT-X-KEY:METHOD=NONE\n")
		}
		plain := payload(fmt.Sprintf("seg%d", i), 1000+i*37)
		want = append(want, plain...)
		var body []byte
		switch {
		case i < 3:
			body = encrypt(t, plain, key1, explicitIV)
		case i < 5:
			body = encrypt(t, plain, key2, ivFromSequence(seq))
		default:
			body = plain
		}
		s.set(fmt.Sprintf("/enc/s%d.ts", i), body)
		fmt.Fprintf(&pl, "#EXTINF:4,\ns%d.ts\n", i)
	}
	pl.WriteString("#EXT-X-ENDLIST\n")
	s.set("/enc/stream.m3u8", []byte(pl.String()))

	m := newManager(t, testProto(NewHLS(Options{}), false))
	d, err := m.Add(engine.Request{URL: s.URL + "/enc/stream.m3u8?token=secret"})
	if err != nil {
		t.Fatal(err)
	}
	done := waitFor(t, m, d.ID, engine.StatusCompleted, 10*time.Second)
	checkFile(t, done, "stream.ts", want)
	if s.hitCount("/keys/k1") != 1 || s.hitCount("/keys/k2") != 1 {
		t.Fatalf("keys fetched %d/%d times, want once each", s.hitCount("/keys/k1"), s.hitCount("/keys/k2"))
	}
}

// TestHLSByteRangeAndMap: fragmented MP4 in one file addressed by byte ranges, with an
// EXT-X-MAP init segment written once; the output is .mp4 even without ffmpeg.
func TestHLSByteRangeAndMap(t *testing.T) {
	s := newServer(t)
	init := payload("init", 500)
	frags := [][]byte{payload("f0", 1200), payload("f1", 900), payload("f2", 1500)}
	file := append([]byte{}, init...)
	for _, f := range frags {
		file = append(file, f...)
	}
	s.set("/fmp4/main.mp4", file)
	pl := fmt.Sprintf(`#EXTM3U
#EXT-X-VERSION:7
#EXT-X-TARGETDURATION:4
#EXT-X-PLAYLIST-TYPE:VOD
#EXT-X-MAP:URI="main.mp4",BYTERANGE="500@0"
#EXTINF:4,
#EXT-X-BYTERANGE:1200@500
main.mp4
#EXTINF:4,
#EXT-X-BYTERANGE:900
main.mp4
#EXTINF:4,
#EXT-X-BYTERANGE:%d
main.mp4
`, 1500)
	s.set("/fmp4/video.m3u8", []byte(pl))
	m := newManager(t, testProto(NewHLS(Options{}), false))
	d, err := m.Add(engine.Request{URL: s.URL + "/fmp4/video.m3u8"})
	if err != nil {
		t.Fatal(err)
	}
	done := waitFor(t, m, d.ID, engine.StatusCompleted, 10*time.Second)
	checkFile(t, done, "video.mp4", file)
}

func TestHLSPauseResume(t *testing.T) {
	s := newServer(t)
	s.with(func() { s.delay = 25 * time.Millisecond })
	want := mediaPlaylist(s, "/pr", 40, 20_000)
	p := testProto(NewHLS(Options{Parallel: 2}), false)
	m := newManager(t, p)
	d, err := m.Add(engine.Request{URL: s.URL + "/pr/index.m3u8"})
	if err != nil {
		t.Fatal(err)
	}
	waitBytes(t, m, d.ID, 8*20_000)
	if err := m.Pause(d.ID); err != nil {
		t.Fatal(err)
	}
	paused := waitFor(t, m, d.ID, engine.StatusPaused, 5*time.Second)
	var st state
	if err := json.Unmarshal(paused.ProtoState, &st); err != nil {
		t.Fatalf("state %q: %v", paused.ProtoState, err)
	}
	if len(st.Tracks) != 1 || st.Tracks[0].Next < 5 || st.Tracks[0].Bytes != st.Tracks[0].Next*20_000 || st.Complete {
		t.Fatalf("saved state = %+v", st)
	}
	if paused.Filename != "index.ts" {
		t.Fatalf("name = %q", paused.Filename)
	}
	// Garbage after the saved length (an unfinished write) must be cut off on resume.
	f, err := os.OpenFile(paused.PartPath(), os.O_WRONLY|os.O_APPEND, 0)
	if err != nil {
		t.Fatal(err)
	}
	_, _ = f.Write(bytes.Repeat([]byte{0xEE}, 7777))
	_ = f.Close()
	if err := m.Resume(d.ID); err != nil {
		t.Fatal(err)
	}
	done := waitFor(t, m, d.ID, engine.StatusCompleted, 15*time.Second)
	checkFile(t, done, "index.ts", want)
	for i := range int(st.Tracks[0].Next) {
		if n := s.hitCount(fmt.Sprintf("/pr/seg%d.ts", i)); n != 1 {
			t.Fatalf("segment %d fetched %d times; resume should continue from segment %d", i, n, st.Tracks[0].Next)
		}
	}
}

// livePlaylist serves a sliding-window live playlist that gains one segment per request
// and, once total segments exist, ends with EXT-X-ENDLIST (end < 0: never ends).
func livePlaylist(s *server, path string, end int) func() []byte {
	var n atomic.Int32
	return func() []byte {
		k := int(n.Add(1))
		if end >= 0 {
			k = min(k, end)
		}
		var b strings.Builder
		first := max(0, k-3) // window of 3
		fmt.Fprintf(&b, "#EXTM3U\n#EXT-X-TARGETDURATION:1\n#EXT-X-MEDIA-SEQUENCE:%d\n", first)
		for i := first; i < k; i++ {
			name := fmt.Sprintf("/live/l%d.ts", i)
			s.set(name, payload(name, 4000))
			fmt.Fprintf(&b, "#EXTINF:1,\nl%d.ts\n", i)
		}
		if end >= 0 && k >= end {
			b.WriteString("#EXT-X-ENDLIST\n")
		}
		return []byte(b.String())
	}
}

