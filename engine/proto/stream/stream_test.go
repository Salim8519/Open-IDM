// TestSecretsStayOnOrigin: Cookie goes to the playlist's host, not to a CDN elsewhere,
// and non-http URIs in a playlist are refused.
func TestSecretsStayOnOrigin(t *testing.T) {
	origin, cdn := newServer(t), newServer(t)
	cdnURL := strings.Replace(cdn.URL, "127.0.0.1", "localhost", 1)
	cdn.set("/c/a.ts", payload("a", 100))
	origin.set("/p/x.m3u8", []byte("#EXTM3U\n#EXT-X-TARGETDURATION:1\n#EXTINF:1,\n"+cdnURL+"/c/a.ts\n#EXT-X-ENDLIST\n"))
	origin.set("/p/bad.m3u8", []byte("#EXTM3U\n#EXT-X-TARGETDURATION:1\n#EXTINF:1,\nfile:///etc/passwd\n#EXT-X-ENDLIST\n"))
	m := newManager(t, testProto(NewHLS(Options{}), false))
	d, err := m.Add(engine.Request{URL: origin.URL + "/p/x.m3u8", Headers: map[string]string{"Cookie": "sid=42"}})
	if err != nil {
		t.Fatal(err)
	}
	waitFor(t, m, d.ID, engine.StatusCompleted, 10*time.Second)
	if oc := origin.cookieList(); oc[0] != "sid=42" {
		t.Fatalf("origin did not get the cookie: %q", oc)
	}
	for _, c := range cdn.cookieList() {
		if c != "" {
			t.Fatalf("cookie leaked to another host: %q", c)
		}
	}
	bad, err := m.Add(engine.Request{URL: origin.URL + "/p/bad.m3u8"})
	if err != nil {
		t.Fatal(err)
	}
	failed := waitFor(t, m, bad.ID, engine.StatusError, 10*time.Second)
	if !strings.Contains(failed.Error, "scheme") {
		t.Fatalf("error = %q", failed.Error)
	}
}

