// TestHLSLivePauseEndsRecording: pausing a live recording keeps what was recorded and
// the next run finishes the file without fetching more.
func TestHLSLivePauseEndsRecording(t *testing.T) {
	s := newServer(t)
	s.setDynamic("/live/tv.m3u8", livePlaylist(s, "/live/tv.m3u8", -1))
	m := newManager(t, testProto(NewHLS(Options{}), false))
	d, err := m.Add(engine.Request{URL: s.URL + "/live/tv.m3u8"})
	if err != nil {
		t.Fatal(err)
	}
	waitBytes(t, m, d.ID, 3*4000)
	if err := m.Pause(d.ID); err != nil {
		t.Fatal(err)
	}
	paused := waitFor(t, m, d.ID, engine.StatusPaused, 5*time.Second)
	var st state
	_ = json.Unmarshal(paused.ProtoState, &st)
	if !st.Live || !st.Stopped {
		t.Fatalf("state = %+v", st)
	}
	reloads := s.hitCount("/live/tv.m3u8")
	if err := m.Resume(d.ID); err != nil {
		t.Fatal(err)
	}
	done := waitFor(t, m, d.ID, engine.StatusCompleted, 5*time.Second)
	if s.hitCount("/live/tv.m3u8") != reloads {
		t.Fatal("playlist reloaded after the recording was stopped")
	}
	var want []byte
	for i := range int(st.Tracks[0].Next) {
		name := fmt.Sprintf("/live/l%d.ts", i)
		want = append(want, payload(name, 4000)...)
	}
	checkFile(t, done, "tv.ts", want)
}

